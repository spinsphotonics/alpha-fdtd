"""cudagen6: CUDA text of one z-stream kernel from the gen3 IR (TMA bulk copies, mbarriers, producer warps).

The ctl flags of the committed kernels (gen.py BASE) select the layout and the copy machinery:
  nofb ctrim nopoll mrg uwait onewait  barrier and wait structure of a beat (no final barrier, one mbarrier per beat, waits by every
                                       thread, merged control region, progress words re-read only when needed)
  cx dup pm ct cp                      coefficients out of the x hand-off record; field array pair-major; per-cell coefficient array
                                       [row][plane][pair][30 lanes] (lanes 24..29 repeat row J + 1), one contiguous load per beat
  pw3                                  a producer warpgroup of 3 warps runs every bulk copy (stream loads, x/y slabs, stores, publish)
  xt                                   trimmed x hand-off slabs (only the lanes a later level reads)
  gt                                   globaltimer at the start and end of the beat loop (timing words, no effect on results)
  dxp                                  consumed x/y slabs dropped from L2 (discard.global.L2) instead of written back

Shared memory of one block: mailboxes (E and H halos), NSI stream-input slots, stream-output slots, x hand-off slabs in and
out, y halo slabs, mbarriers and 16 control pointers.  Synchronisation is by proven order, no timing margin: the producer of
beat b commits store group b, waits for groups <= b - WGP and publishes v = b - WGP + 1; a consumer loads x slab s only after
reading v_x >= s + 2 and y slab s only after v_y >= s + 1.
"""
from gen3 import GOFF, F6, C6

def layout(gen):
    k, R, S, Gh = (gen.k, gen.R, gen.S, gen.Gh)
    L = {}
    o = 0

    def add(name, n):
        nonlocal o
        L[name] = o
        o += n
    L['MBSZ'] = 2 * 8 * R * 32 * 4
    OS = 4
    fl = gen.ctl.split('+')
    L['CR'] = 24
    L['SINSZ'] = 9 * 32 * 48
    L['SOUTSZ'] = 8 * S * (24 if gen.split else 48) + 64
    L['XSZ'] = (k - 1) * 32 * gen.XREC + 256
    L['YSZ'] = k * 64
    assert gen.cx
    L['XN'] = [31 - r for r in range(k - 1)] + [32 - k]
    L['XN'] = [n - 1 for n in L['XN']]
    L['XOFF'] = [12 * sum(L['XN'][:r]) for r in range(k)]
    L['XSZ'] = (L['XOFF'][k - 1] + 4 * L['XN'][k - 1] + 15) // 16 * 16
    L['CHSZ'] = 3 * 32 * L['CR']
    add('MB', L['MBSZ'])
    add('SIN', gen.NSI * L['SINSZ'])
    add('SOUT', OS * L['SOUTSZ'])
    add('XPI', 4 * L['XSZ'])
    add('XPO', OS * L['XSZ'])
    add('YHI', 4 * L['YSZ'])
    add('YHO', OS * L['YSZ'])
    if gen.cx:
        add('CH', (16 if gen.cx else 1) * L['CHSZ'])
    add('MBAR', (2 * gen.NSI + 8) * 8)
    add('CTL', 56 * 8)
    L['JNKSZ'] = max([int(f[2:]) for f in fl if f[:2] in ('jr', 'jw') and f[2:].isdigit()] + [0])
    L['TOTAL'] = (o + 127) // 128 * 128
    return L

